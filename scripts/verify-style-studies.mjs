// Run against a built Patchwork preview. Uses a fresh browser context, never the user's profile.
// PATCHWORK_QA_URL=http://127.0.0.1:5188 PATCHWORK_CHROME=/path/to/chrome node scripts/verify-style-studies.mjs
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import JSZip from 'jszip';
const base = process.env.PATCHWORK_QA_URL || 'http://127.0.0.1:5188';
const browser = await chromium.launch({ executablePath: process.env.PATCHWORK_CHROME || undefined, headless: true });
const context = await browser.newContext({ viewport: {width:1440,height:1000}, acceptDownloads: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const openGallery = () => page.goto(`${base}/?collection=library&library=styles`);
const frame = () => page.frameLocator('iframe[title$="interactive website"]');
try {
  await openGallery();
  await page.locator('.ss-card').first().waitFor();
  assert.equal(await page.locator('.ss-card').count(), 28);
  await page.waitForFunction(() => [...document.querySelectorAll('.ss-card-open>img')].slice(0,3).every(img => img.complete && img.naturalWidth>0));
  await page.getByRole('combobox',{name:'Style family'}).selectOption('Nature & craft');
  assert.equal(await page.locator('.ss-card').count(),1);
  await page.getByRole('combobox',{name:'Style family'}).selectOption('all');
  await page.getByRole('textbox',{name:'Search style studies'}).fill('minimalist kaelen');
  assert.equal(await page.locator('.ss-card').count(),1);
  await page.getByRole('button',{name:'Save Kaelen Vance',exact:true}).click();
  await page.getByRole('button',{name:'Clear search',exact:true}).click();
  await page.getByRole('button',{name:/^Saved /}).click();
  assert.equal(await page.locator('.ss-card').count(),1);
  await page.reload();
  await page.getByRole('button',{name:'Unsave Kaelen Vance',exact:true}).waitFor();
  await page.getByRole('button',{name:'Start live preview of Kaelen Vance',exact:true}).click();
  await page.locator('.ss-playing').waitFor();
  assert.equal(await page.locator('.ss-live iframe').count(),1);
  await page.waitForFunction(() => {const f=document.querySelector('iframe[title$="live card preview"]');return (f?.contentDocument?.scrollingElement?.scrollTop||0)>15;});
  await page.getByRole('button',{name:'Stop live preview of Kaelen Vance',exact:true}).click();
  assert.equal(await page.locator('.ss-live iframe').count(),0);
  await page.getByRole('button',{name:'Explore Kaelen Vance',exact:true}).click();
  await page.locator('.ss-live[aria-busy=false]').waitFor();
  assert.ok(page.url().includes('study=minimalist'));
  assert.equal(await frame().locator('body').evaluate(() => innerWidth),1280);
  const work=frame().getByRole('button',{name:/Aetheria Distributed Consensus/});
  await work.focus(); await page.keyboard.press('Enter');
  await frame().getByRole('button',{name:/Aetheria Distributed Consensus/,expanded:false}).waitFor();
  await page.keyboard.press('Enter');
  await frame().getByRole('button',{name:/Aetheria Distributed Consensus/,expanded:true}).waitFor();
  await page.getByRole('button',{name:'Tablet preview',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('iframe[title$="interactive website"]')?.contentWindow?.innerWidth===768);
  await page.getByRole('button',{name:'Phone preview',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('iframe[title$="interactive website"]')?.contentWindow?.innerWidth===390);
  await page.getByRole('button',{name:'Expand preview',exact:true}).click();
  assert.equal(await page.locator('.ss-expanded').count(),1);
  await page.keyboard.press('Escape');
  await page.locator('.style-studio:not(.ss-expanded)').waitFor();
  assert.equal(await page.locator('.style-studio').count(),1);
  await page.keyboard.press('Escape');
  await page.locator('.ss-card').first().waitFor();
  assert.equal(await page.locator('.ss-card').count(),28);
  await page.getByRole('textbox',{name:'Search style studies'}).fill('no such study 93721');
  await page.getByRole('heading',{name:'No studies found.',exact:true}).waitFor();
  await page.getByRole('button',{name:'Show all studies',exact:true}).click();
  assert.equal(await page.locator('.ss-card').count(),28);
  const downloaded = page.waitForEvent('download');
  await page.getByRole('link',{name:'Download library source',exact:true}).click();
  const archive=await JSZip.loadAsync(await fs.readFile(await (await downloaded).path()));
  assert.ok(archive.file('src/websites/minimalist/index.tsx'));
  assert.ok(archive.file('src/redesign/fonts/Outfit-OFL.txt'));
  for(const width of [1440,1024,768,390,320]) {
    await page.setViewportSize({width,height:900});
    const overflow=await page.evaluate(() => document.documentElement.scrollWidth>innerWidth);
    assert.equal(overflow,false,`Gallery overflow at ${width}`);
  }
  await page.getByRole('button',{name:'Explore Kaelen Vance',exact:true}).click();
  await page.locator('.ss-live[aria-busy=false]').waitFor();
  for(const width of [1440,1024,768,390,320]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth>innerWidth),false,`Preview workspace overflow at ${width}`);
  }
  await page.getByRole('link',{name:'Open website in a new tab',exact:true}).waitFor();
  const popupPromise=page.waitForEvent('popup');
  await page.getByRole('link',{name:'Open website in a new tab',exact:true}).click();
  const popup=await popupPromise;await popup.locator('.style-study').waitFor();
  assert.equal(await popup.locator('.design-library-workspace').count(),0);
  await popup.close();
  await page.setViewportSize({width:390,height:844});
  const catalog=JSON.parse(await fs.readFile(new URL('../vendor/design-library/src/library-catalog.json',import.meta.url),'utf8'));
  for(const study of catalog.entries.filter(e=>e.kind==='styles')) {
    await page.goto(`${base}/?collection=library&library=styles&study=${study.originalId}`);
    await page.locator('.ss-live[aria-busy=false]').waitFor({timeout:20000});
    await page.getByRole('button',{name:'Phone preview',exact:true}).click();
    await page.waitForFunction(() => document.querySelector('iframe[title$="interactive website"]')?.contentWindow?.innerWidth===390);
    assert.ok(await frame().locator('.style-study').textContent(),study.originalId);
    assert.equal(await frame().locator('body').evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`Study overflow: ${study.originalId}`);
  }
  await context.setOffline(true);
  // Already-loaded local study remains interactive offline; no network API is required.
  assert.ok(await frame().locator('.style-study').textContent());
  await context.setOffline(false);
  await context.grantPermissions(['clipboard-read','clipboard-write']);
  await page.getByRole('button',{name:'Copy study link',exact:true}).click();
  assert.ok((await page.evaluate(()=>navigator.clipboard.readText())).includes('study=experimental'));
  const reduced=await browser.newContext({viewport:{width:1280,height:900},reducedMotion:'reduce'});
  const reducedPage=await reduced.newPage();
  await reducedPage.goto(`${base}/?collection=library&library=styles`);
  await reducedPage.getByRole('button',{name:'Start live preview of Kaelen Vance',exact:true}).click();
  await reducedPage.locator('.ss-playing').waitFor();
  const reducedFrame=reducedPage.frameLocator('iframe[title$="live card preview"]');
  const first=await reducedFrame.locator('body').evaluate(()=>document.scrollingElement.scrollTop);
  await reducedPage.waitForTimeout(700);
  assert.equal(await reducedFrame.locator('body').evaluate(()=>document.scrollingElement.scrollTop),first);
  await reduced.close();
  const errorPage=await context.newPage();
  await errorPage.clock.install();
  await errorPage.route(/\/design-library\/index\.html\?embedded=1/, route=>route.abort());
  await errorPage.goto(`${base}/?collection=library&library=styles&study=minimalist`);
  await errorPage.locator('.ss-live[aria-busy=true]').waitFor();
  await errorPage.clock.fastForward(16000);
  await errorPage.getByRole('alert').waitFor();
  await errorPage.unroute(/\/design-library\/index\.html\?embedded=1/);
  await errorPage.getByRole('button',{name:'Try again',exact:true}).click();
  await errorPage.clock.resume();
  await errorPage.locator('.ss-live[aria-busy=false]').waitFor();
  assert.equal(await errorPage.getByRole('alert').count(),0);
  await errorPage.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: 28 live studies; gallery/search/saved persistence; preview start/stop; three viewport widths; Escape; independent tab; source ZIP download; error/retry; clipboard; responsive shell 320–1440; reduced motion.');
} finally {await browser.close();}
